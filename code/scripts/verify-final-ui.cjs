const {chromium}=require('playwright');
const {expect}=require('@playwright/test');
const fs=require('fs'),path=require('path');
(async()=>{
 const report={observed_at:new Date().toISOString(),checks:[],pageErrors:[]};
 const user=require('../.runtime/rehearsal-users.json').owner;
 const id=require('../.runtime/aws-rehearsal.json').mutations.find(m=>m.operation==='final application multipart upload').file_id;
 const browser=await chromium.launch({headless:true,executablePath:path.join(process.env.PROGRAMFILES,'BraveSoftware/Brave-Browser/Application/brave.exe')});
 const page=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'reduce'});
 page.on('pageerror',e=>report.pageErrors.push(e.message));
 try{
  await page.goto('http://127.0.0.1:3100/login');
  await page.getByLabel('Email address').fill(user.email);
  await page.getByLabel('Password',{exact:true}).fill(user.password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL('**/dashboard');
  await expect(page.getByText('File types · 1 locally indexed',{exact:true})).toBeVisible();
  await expect(page.getByText('Uploads · last 7 days (UTC)',{exact:true})).toBeVisible();
  for(const width of [360,390,1366]){
   await page.setViewportSize({width,height:844});
   await page.goto('http://127.0.0.1:3100/dashboard');
   await page.waitForLoadState('networkidle');
   await expect(page.getByText('File types · 1 locally indexed',{exact:true})).toBeVisible();
   if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))throw new Error('Dashboard overflow');
   await page.screenshot({path:`.runtime/screenshots/dashboard-final-${width}.png`,fullPage:true});
   await page.goto('http://127.0.0.1:3100/ask?fileId='+id);
   await expect(page.getByText('Selected document only',{exact:true})).toBeVisible();
   if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))throw new Error('Scoped Ask overflow');
   report.checks.push({width,dashboard_real_statistics:true,document_scope_badge:true,no_horizontal_overflow:true});
  }
  await page.setViewportSize({width:1366,height:844});
  const scope=page.getByLabel('Document folder scope');
  await scope.focus();
  await expect(scope.locator('option',{hasText:'Native rehearsal'})).toHaveCount(1);
  await scope.selectOption({label:'Native rehearsal'});
  await page.getByRole('tab',{name:'Semantic search',exact:true}).click();
  await page.getByLabel('Semantic search query').fill('MiniLM Qwen local laptop');
  const response=page.waitForResponse(r=>r.url().endsWith('/ai/search')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  const data=(await (await response).json()).data;
  if(data.results.length!==1||data.awsCalls!==0||typeof data.retrievalMs!=='number')throw new Error('Actual scoped hybrid search failed');
  await expect(page.getByText(/1 matching documents/)).toBeVisible();
  await page.getByLabel('Search mode',{exact:true}).selectOption('lexical');
  const lexical=page.waitForResponse(r=>r.url().endsWith('/ai/search')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  if((await (await lexical).json()).data.results[0]?.scoreKind!=='lexical')throw new Error('BM25 did not return keyword ranking');
  await expect(page.getByText('Keyword match',{exact:true})).toBeVisible();
  await page.getByLabel('Search mode',{exact:true}).selectOption('exact');
  await page.getByLabel('Semantic search query').fill('MiniLM embeddings');
  const exact=page.waitForResponse(r=>r.url().endsWith('/ai/search')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  if((await (await exact).json()).data.results[0]?.scoreKind!=='literal')throw new Error('Exact mode score label was not literal');
  await expect(page.getByText('Exact match',{exact:true})).toBeVisible();
  report.checks.push({actual_BM25_keyword_badge:true,actual_exact_match_badge:true});
  await page.getByLabel('Document type filter').selectOption('image');
  const filtered=page.waitForResponse(r=>r.url().endsWith('/ai/search')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  if((await (await filtered).json()).data.results.length!==0)throw new Error('Type filter failed');
  report.checks.push({actual_nested_folder_scope:true,recovered_hybrid_query:true,type_filter:true,measured_server_latency_ms:data.retrievalMs});
  await page.goto('http://127.0.0.1:3100/ask?fileId='+id+'&task=summary');
  await expect(page.getByLabel('Your question')).toHaveValue(/retrieved excerpts/);
  report.checks.push({selected_document_summary_action:true});
  await page.goto('http://127.0.0.1:3100/');
  await page.getByRole('button',{name:'Switch to light theme',exact:true}).click();
  await expect(page.locator('main.light-mode')).toBeVisible();
  await page.screenshot({path:'.runtime/screenshots/landing-light-final.png',fullPage:true});
  await page.getByRole('button',{name:'Switch to dark theme',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Open menu',exact:true}).click();
  await expect(page.getByRole('button',{name:'Close menu',exact:true})).toBeVisible();
  if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1))throw new Error('Mobile landing menu overflow');
  report.checks.push({light_theme:true,dark_theme:true,mobile_navigation:true});
  report.result=report.pageErrors.length?'failed':'passed';
  if(report.result!=='passed')throw new Error('Browser page errors');
  fs.writeFileSync(require('node:path').resolve(__dirname, '../../docs/FINAL_UI_ACCEPTANCE.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
 }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exit(1)});
