import { expect, test } from '@playwright/test'
import { readFile } from 'fs/promises'
import { API, apiFolder, apiShare, apiUpload, bearer, newAccount, rowAction, textFile, uploadViaUi, watchErrors } from './helpers'

test('share a file, change the role, revoke it', async ({ browser, request }) => {
  const owner = await newAccount(browser, request, 'Olive Owner')
  const guest = await newAccount(browser, request, 'Gus Guest')
  const errors = watchErrors(guest.page)
  await apiUpload(request, owner, 'contract.txt', 'terms')

  await owner.page.goto('/files')
  await rowAction(owner.page, 'contract.txt', 'Share with people')
  const dialog = owner.page.getByRole('dialog')
  await dialog.getByLabel('Email address').fill('nobody-here@e2e.test')
  await dialog.getByRole('button', { name: /invite|share|add/i }).first().click()
  await expect(dialog.getByText(/not found|no nimbusvault account|couldn/i).first()).toBeVisible()
  await dialog.getByLabel('Email address').fill(guest.email)
  await dialog.getByRole('button', { name: /invite|share|add/i }).first().click()
  await expect(dialog.getByText('Gus Guest')).toBeVisible()

  await guest.page.goto('/shared-with-me')
  await expect(guest.page.getByText('contract.txt')).toBeVisible()
  await expect(guest.page.getByRole('cell', { name: 'Viewer' })).toBeVisible()

  await dialog.getByLabel('Role for Gus Guest').selectOption('EDITOR')
  await guest.page.reload()
  await expect(guest.page.getByRole('cell', { name: 'Editor' })).toBeVisible()
  await rowAction(guest.page, 'contract.txt', 'Rename')
  await guest.page.getByRole('dialog').getByLabel('Name').fill('contract-v2.txt')
  await guest.page.getByRole('dialog').getByRole('button', { name: 'Save' }).click()
  await expect(guest.page.getByRole('cell', { name: 'contract-v2.txt' }).first()).toBeVisible()

  await dialog.getByRole('button', { name: 'Remove Gus Guest' }).click()
  await dialog.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(dialog.getByText('Only you have access')).toBeVisible()
  await guest.page.reload()
  await expect(guest.page.getByText('No files shared with you')).toBeVisible()
  expect(errors).toEqual([])
})

test('shared folder: viewers browse, editors upload, and the owner sees it all', async ({ browser, request }) => {
  const owner = await newAccount(browser, request, 'Fay Owner')
  const viewer = await newAccount(browser, request, 'Vic Viewer')
  const editor = await newAccount(browser, request, 'Eve Editor')
  const folder = await apiFolder(request, owner, 'Team')
  const sub = await apiFolder(request, owner, 'Nested', folder)
  await apiUpload(request, owner, 'inside.txt', 'x', sub)
  await apiShare(request, owner, 'FOLDER', folder, viewer, 'VIEWER')
  await apiShare(request, owner, 'FOLDER', folder, editor, 'EDITOR')

  await viewer.page.goto('/shared-with-me')
  await viewer.page.getByRole('tab', { name: /Folders/ }).click()
  await viewer.page.getByRole('link', { name: 'Open' }).click()
  await viewer.page.getByRole('link', { name: 'Nested' }).click()
  await expect(viewer.page.getByText('inside.txt')).toBeVisible()
  await expect(viewer.page.getByRole('button', { name: 'Upload' })).toHaveCount(0)

  await editor.page.goto(`/shared-with-me/folders/${folder}`)
  await uploadViaUi(editor.page, [textFile('from-editor.txt', 'hello')])
  await expect(editor.page.getByText('from-editor.txt').first()).toBeVisible()
  await owner.page.goto(`/files/${folder}`)
  await expect(owner.page.getByText('from-editor.txt').first()).toBeVisible()
  await expect(owner.page.getByText(/6 B of 5 GB used/).first()).toBeVisible()

  await owner.page.goto('/shared-with-me')
  await owner.page.getByRole('tab', { name: 'Shared by you' }).click()
  await expect(owner.page.getByText('Vic Viewer')).toBeVisible()
  await expect(owner.page.getByRole('button', { name: 'Manage access to Team' })).toBeVisible()
})

test('owner, editor, viewer and stranger boundaries hold at the API', async ({ browser, request }) => {
  const owner = await newAccount(browser, request, 'Api Owner')
  const viewer = await newAccount(browser, request, 'Api Viewer')
  const stranger = await newAccount(browser, request, 'Api Stranger')
  const file = await apiUpload(request, owner, 'a.txt', 'x')
  await apiShare(request, owner, 'FILE', file, viewer, 'VIEWER')
  const status = async (a: typeof owner, method: 'get' | 'patch' | 'delete', path: string, data?: object) => (await request[method](`${API}${path}`, { headers: bearer(a), data })).status()
  expect(await status(viewer, 'get', `/files/${file}/download`)).toBe(200)
  expect(await status(viewer, 'patch', `/files/${file}/rename`, { filename: 'b.txt' })).toBe(403)
  expect(await status(viewer, 'delete', `/files/${file}`)).toBe(403)
  for (const path of [`/files/${file}`, `/files/${file}/download`, `/ai/files/${file}`, `/activity/resource/FILE/${file}`, `/share-links/protected/${file}`]) {
    expect([403, 404]).toContain(await status(stranger, 'get', path))
  }
  expect(await status(stranger, 'get', `/activity?userId=${owner.id}`)).toBe(403)
})

test('share link: password, download, limit, revoke', async ({ browser, request }) => {
  const owner = await newAccount(browser, request, 'Link Owner')
  await apiUpload(request, owner, 'brochure.txt', 'public content')
  await owner.page.goto('/files')
  await rowAction(owner.page, 'brochure.txt', 'Create share link')
  const dialog = owner.page.getByRole('dialog')
  await dialog.getByLabel(/^Password/).fill('pässwörd1')
  await dialog.getByLabel(/^Download limit/).fill('1')
  await dialog.getByRole('button', { name: /create link/i }).click()
  const url = await dialog.getByLabel('New share link').inputValue()
  expect(url).toMatch(/^http:\/\/localhost:4173\/share\/[\w-]{43}$/)

  const anon = await (await browser.newContext()).newPage()
  const errors = watchErrors(anon)
  await anon.goto(url)
  await anon.getByLabel('Password', { exact: true }).fill('wrong')
  await anon.getByRole('button', { name: 'Unlock file' }).click()
  await expect(anon.getByRole('alert')).toBeVisible()
  await anon.getByLabel('Password', { exact: true }).fill('pässwörd1')
  await anon.getByRole('button', { name: 'Unlock file' }).click()
  await expect(anon.getByRole('heading', { name: 'brochure.txt' })).toBeVisible()
  const [download] = await Promise.all([anon.waitForEvent('download'), anon.getByRole('button', { name: 'Download file' }).click()])
  expect(await readFile(await download.path(), 'utf8')).toBe('public content')

  await anon.goto(url)
  await expect(anon.getByText('Download limit reached')).toBeVisible()
  expect(errors).toEqual([])

  await dialog.getByRole('button', { name: 'Done' }).click()
  await rowAction(owner.page, 'brochure.txt', 'Create share link')
  await dialog.getByRole('button', { name: /create link/i }).click()
  const second = await dialog.getByLabel('New share link').inputValue()
  await anon.goto(second)
  await expect(anon.getByRole('heading', { name: 'brochure.txt' })).toBeVisible()
  await dialog.getByRole('button', { name: /^Revoke/ }).first().click()
  await dialog.getByRole('button', { name: 'Revoke', exact: true }).last().click()
  await expect(dialog.getByText('Revoked').first()).toBeVisible()
  await anon.reload()
  await expect(anon.getByText('This link was turned off')).toBeVisible()
})

test('expired links and invalid tokens explain themselves', async ({ browser, request, page }) => {
  const owner = await newAccount(browser, request, 'Expiry Owner')
  const file = await apiUpload(request, owner, 'soon.txt', 'x')
  const res = await request.post(`${API}/share-links/protected`, { headers: bearer(owner), data: { fileId: file, permission: 'VIEW', expiresAt: new Date(Date.now() + 2500).toISOString() } })
  const { token } = (await res.json()).data
  await page.goto(`/share/${token}`)
  await expect(page.getByRole('heading', { name: 'soon.txt' })).toBeVisible()
  await expect(page.getByText(/downloading is turned off/)).toBeVisible()
  await page.waitForTimeout(2700)
  await page.reload()
  await expect(page.getByText('This link has expired')).toBeVisible()
  await page.goto('/share/not-a-real-token-at-all-000000')
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await expect(page.getByText(/isn.t valid|not found|unavailable|doesn.t exist|no longer/i).first()).toBeVisible()
})

